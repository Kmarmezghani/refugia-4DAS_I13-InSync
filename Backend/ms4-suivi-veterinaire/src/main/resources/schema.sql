CREATE TABLE IF NOT EXISTS dossier_medical (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id BIGINT NOT NULL UNIQUE,
    numero_dossier VARCHAR(255) NOT NULL,
    date_ouverture DATE NOT NULL,
    notes_generales TEXT
);

CREATE TABLE IF NOT EXISTS consultation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dossier_id BIGINT NOT NULL REFERENCES dossier_medical(id),
    date_consultation DATE NOT NULL,
    motif TEXT NOT NULL,
    diagnostic TEXT,
    poids DOUBLE PRECISION,
    temperature DOUBLE PRECISION,
    remarques TEXT
);

CREATE INDEX IF NOT EXISTS idx_consultation_historique
    ON consultation (dossier_id, date_consultation DESC, id DESC);

CREATE TABLE IF NOT EXISTS vaccination (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dossier_id BIGINT NOT NULL REFERENCES dossier_medical(id),
    vaccin TEXT NOT NULL,
    date_vaccination DATE NOT NULL,
    date_rappel DATE CHECK (date_rappel >= date_vaccination),
    rappel_publie BOOLEAN NOT NULL DEFAULT FALSE,
    statut VARCHAR(255) NOT NULL CHECK (statut IN ('A_JOUR', 'A_RAPPELER', 'EN_RETARD'))
);

CREATE INDEX IF NOT EXISTS idx_vaccination_historique
    ON vaccination (dossier_id, date_vaccination DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_vaccination_rappel
    ON vaccination (date_rappel, id);

CREATE TABLE IF NOT EXISTS traitement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dossier_id BIGINT NOT NULL REFERENCES dossier_medical(id),
    medicament TEXT NOT NULL,
    posologie TEXT NOT NULL,
    date_debut DATE NOT NULL,
    date_fin DATE CHECK (date_fin >= date_debut),
    statut VARCHAR(255) NOT NULL CHECK (statut IN ('EN_COURS', 'TERMINE', 'SUSPENDU'))
);

CREATE INDEX IF NOT EXISTS idx_traitement_dossier
    ON traitement (dossier_id, date_debut DESC, id DESC);
